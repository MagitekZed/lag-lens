#!/usr/bin/env python3
"""Build the Lag Lens distribution: lag-lens.zip plus the Pages site files.

Standard library only (Python 3.9+). Run from anywhere:

    python3 build/make_zip.py [--out DIR] [--strict] [--repo PATH] [--base-url URL]
                              [--previous LIVE_VERSION_JSON]

A relative --out is resolved against the current directory (like any CLI);
the default is <repo>/site. --previous takes a copy of the version.json that
is live on the site right now; the Pages workflow fetches it so the new
version.json can carry a `previous` entry (version, url, sha256) that
`start.sh --update --version X` uses to roll back (SPEC_FULL §12.6).

Rebuilds are byte-identical on one machine, but zlib output differs between
platforms (macOS vs. Ubuntu), so a locally built sha256 need not match the
published one. The sha256 published on the site is authoritative; get.sh
verifies against that.

What it does (see docs/BUILD_PLAN.md §2 and docs/design/SPEC_FULL.md §12.2):

* reads VERSION at the repo root;
* writes laglens/version.py ONLY if it does not exist yet (the package owns that
  file; the build passes the version through the VERSION file in the zip);
* builds <out>/lag-lens.zip with a top-level lag-lens/ folder containing
  run.py start.sh get.sh config.example.json README.md LICENSE CHANGELOG.md
  VERSION laglens/** (minus __pycache__, *.pyc, .DS_Store, sessions, config.json);
* sets executable bits on start.sh / get.sh / run.py and fixes every member's
  timestamp to the last git commit time (or 2026-01-01) so rebuilds are byte-identical;
* writes <out>/lag-lens-<version>.zip, <out>/lag-lens.zip.sha256, <out>/VERSION,
  <out>/version.json, <out>/get.sh, <out>/style.css and renders <out>/index.html
  from site/index.html.tmpl.

Missing distributable files are warnings unless --strict is given (CI uses it).
Nothing is written outside the repo except the --out directory you name.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import hashlib
import html
import json
import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path
from typing import List, Optional, Tuple

ZIP_NAME = "lag-lens.zip"
TOP_DIR = "lag-lens"
DEFAULT_BASE_URL = "https://magitekzed.github.io/lag-lens"
FALLBACK_DATE = (2026, 1, 1, 0, 0, 0)

ROOT_FILES = [
    "run.py",
    "start.sh",
    "get.sh",
    "config.example.json",
    "README.md",
    "LICENSE",
    "CHANGELOG.md",
    "VERSION",
]
EXECUTABLE = {"start.sh", "get.sh", "run.py"}
EXCLUDE_DIRS = {"__pycache__", "sessions"}
EXCLUDE_FILES = {".DS_Store", "config.json"}
EXCLUDE_SUFFIXES = (".pyc", ".pyo")

VERSION_PY_TEMPLATE = '''"""Lag Lens package version.

Generated by build/make_zip.py because laglens/version.py was missing. The
authoritative value lives in the VERSION file next to run.py; the literal
below is only a fallback for when that file cannot be read.
"""
import os


def _read_version_file():
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(os.path.dirname(here), "VERSION")
    try:
        with open(path, "r", encoding="utf-8") as fh:
            value = fh.read().strip()
        return value or None
    except OSError:
        return None


__version__ = _read_version_file() or "{version}"
'''


def warn(msg: str) -> None:
    print("make_zip: WARNING: " + msg, file=sys.stderr)


def info(msg: str) -> None:
    print("make_zip: " + msg)


def read_version(repo: Path) -> str:
    path = repo / "VERSION"
    if not path.is_file():
        raise SystemExit("make_zip: VERSION file not found at %s" % path)
    version = path.read_text(encoding="utf-8").strip()
    if not version:
        raise SystemExit("make_zip: VERSION is empty")
    for ch in version:
        if not (ch.isalnum() or ch in ".-+"):
            raise SystemExit("make_zip: VERSION contains an unexpected character: %r" % ch)
    return version


def ensure_version_py(repo: Path, version: str) -> bool:
    """Create laglens/version.py only when it is missing. Returns True if written."""
    pkg = repo / "laglens"
    target = pkg / "version.py"
    if target.exists():
        return False
    pkg.mkdir(parents=True, exist_ok=True)
    target.write_text(VERSION_PY_TEMPLATE.format(version=version), encoding="utf-8")
    info("wrote %s (it was missing)" % target.relative_to(repo))
    return True


def git_commit_time(repo: Path) -> Optional[int]:
    """Unix time of the last commit, or None when not in a git repo / no commits."""
    try:
        out = subprocess.run(
            ["git", "-C", str(repo), "log", "-1", "--format=%ct"],
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if out.returncode != 0:
        return None
    text = out.stdout.strip()
    return int(text) if text.isdigit() else None


def zip_date_time(repo: Path) -> Tuple[int, int, int, int, int, int]:
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    ts: Optional[int] = None
    if epoch and epoch.isdigit():
        ts = int(epoch)
    else:
        ts = git_commit_time(repo)
    if ts is None:
        return FALLBACK_DATE
    d = _dt.datetime.fromtimestamp(ts, tz=_dt.timezone.utc)
    if d.year < 1980:  # zip format cannot represent it
        return FALLBACK_DATE
    return (d.year, d.month, d.day, d.hour, d.minute, d.second)


def collect_members(repo: Path) -> Tuple[List[Tuple[str, Path]], List[str]]:
    """Return ([(arcname, path)], [missing relative paths]) sorted by arcname."""
    members: List[Tuple[str, Path]] = []
    missing: List[str] = []

    for name in ROOT_FILES:
        p = repo / name
        if p.is_file():
            members.append((TOP_DIR + "/" + name, p))
        else:
            missing.append(name)

    pkg = repo / "laglens"
    if not pkg.is_dir():
        missing.append("laglens/")
    else:
        for dirpath, dirnames, filenames in os.walk(pkg):
            dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDE_DIRS)
            for fn in sorted(filenames):
                if fn in EXCLUDE_FILES or fn.endswith(EXCLUDE_SUFFIXES):
                    continue
                full = Path(dirpath) / fn
                rel = full.relative_to(repo).as_posix()
                members.append((TOP_DIR + "/" + rel, full))
        if not any(a.startswith(TOP_DIR + "/laglens/") for a, _ in members):
            missing.append("laglens/** (empty)")

    members.sort(key=lambda m: m[0])
    return members, missing


def build_zip(members: List[Tuple[str, Path]], out_zip: Path, date_time) -> None:
    tmp = out_zip.with_name(out_zip.name + ".tmp")
    with zipfile.ZipFile(tmp, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for arcname, path in members:
            zi = zipfile.ZipInfo(arcname, date_time=date_time)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.create_system = 3  # UNIX, so external_attr carries the mode
            basename = arcname.rsplit("/", 1)[-1]
            mode = 0o755 if basename in EXECUTABLE else 0o644
            zi.external_attr = (0o100000 | mode) << 16
            zf.writestr(zi, path.read_bytes())
    os.replace(tmp, out_zip)


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def changelog_sections(lines: List[str]) -> List[List[str]]:
    """Split CHANGELOG lines into '## ' sections (each list starts with its heading)."""
    sections: List[List[str]] = []
    for line in lines:
        if line.strip().startswith("## "):
            sections.append([line])
        elif sections:
            sections[-1].append(line)
    return sections


def changelog_excerpt(repo: Path, version: Optional[str] = None) -> str:
    """The CHANGELOG.md section for `version` as minimal HTML.

    Keep a Changelog puts an `## [Unreleased]` section first, so the section
    whose heading names the version is preferred; the first section is the
    fallback when none does, and 'initial release' when there is nothing.
    """
    path = repo / "CHANGELOG.md"
    if not path.is_file():
        return "<p>initial release</p>"
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    sections = changelog_sections(lines)
    section: List[str] = []
    if sections:
        section = sections[0]
        if version:
            for cand in sections:
                heading = cand[0].strip()[3:]
                if _heading_names_version(heading, version):
                    section = cand
                    break
    else:
        # No "## " headings: use everything after the title line.
        section = [ln for ln in lines if not ln.startswith("# ")]
    text = "\n".join(section).strip()
    if not text:
        return "<p>initial release</p>"
    return _md_to_html(text)


def _heading_names_version(heading: str, version: str) -> bool:
    """True when a '## ' heading refers to `version` as a whole token.

    "[1.0.0] - 2026-10-11", "1.0.0", "v1.0.0" match 1.0.0; "1.0.0-rc1" or
    "11.0.0" do not.
    """
    pos = 0
    while True:
        i = heading.find(version, pos)
        if i < 0:
            return False
        before = heading[i - 1] if i > 0 else ""
        after = heading[i + len(version)] if i + len(version) < len(heading) else ""
        ok_before = before == "" or before in " [(v"
        ok_after = after == "" or after in " ]):"
        if ok_before and ok_after:
            return True
        pos = i + 1


def _md_to_html(text: str) -> str:
    """Tiny Markdown subset: ## / ### headings, - bullets, paragraphs.

    Wrapped lines (a bullet or paragraph continued on the next line without a
    blank line between) are joined back onto the item they belong to.
    """
    out: List[str] = []
    in_list = False
    buf: List[str] = []  # pending lines of the current <li> or <p>
    buf_kind = ""  # "li" or "p"

    def flush() -> None:
        nonlocal buf, buf_kind
        if buf:
            body = html.escape(" ".join(buf))
            out.append("<%s>%s</%s>" % (buf_kind, body, buf_kind))
        buf, buf_kind = [], ""

    def close_list() -> None:
        nonlocal in_list
        flush()
        if in_list:
            out.append("</ul>")
            in_list = False

    for raw in text.splitlines():
        stripped = raw.strip()
        if not stripped:
            close_list()
            continue
        if stripped.startswith("## "):
            close_list()
            out.append("<h3>%s</h3>" % html.escape(stripped[3:].strip()))
        elif stripped.startswith("### "):
            close_list()
            out.append("<h4>%s</h4>" % html.escape(stripped[4:].strip()))
        elif stripped.startswith(("- ", "* ")):
            flush()
            if not in_list:
                out.append("<ul>")
                in_list = True
            buf, buf_kind = [stripped[2:].strip()], "li"
        elif buf:
            buf.append(stripped)  # continuation of the current bullet/paragraph
        else:
            if in_list:
                close_list()
            buf, buf_kind = [stripped], "p"
    close_list()
    return "\n".join(out)


def render_index(template: Path, out: Path, values: dict) -> None:
    text = template.read_text(encoding="utf-8")
    for key, val in values.items():
        text = text.replace("{{" + key + "}}", val)
    out.write_text(text, encoding="utf-8")


def load_live_version_json(path: Path) -> Optional[dict]:
    """Parse a downloaded copy of the live version.json; None (with a warning) if unusable.

    A missing or empty file is the normal first-deploy case (nothing is live yet)
    and is not a warning.
    """
    if not path.is_file() or path.stat().st_size == 0:
        info("no live version.json at %s; version.json['previous'] will be null" % path)
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        warn("ignoring unreadable live version.json %s: %s" % (path, exc))
        return None
    if not isinstance(data, dict) or not isinstance(data.get("version"), str):
        warn("ignoring live version.json %s: no 'version' string" % path)
        return None
    return data


def previous_entry(live: dict, version: str, base: str) -> Optional[dict]:
    """Compute version.json['previous'] from the version.json that is live now.

    * live is an older (or any different) version: it becomes `previous`, pointing
      at its versioned zip (lag-lens-<ver>.zip) so the file stays addressable
      after lag-lens.zip is replaced;
    * live is this same version (a rebuild, e.g. a docs-only push): keep the
      `previous` the live file already has, so rollback still targets the
      release before this one.
    """
    live_version = live.get("version")
    if live_version != version:
        zip_name = live.get("zip_name")
        if not isinstance(zip_name, str) or not zip_name:
            zip_name = "lag-lens-%s.zip" % live_version
        entry = {"version": live_version, "url": base + "/" + zip_name}
        if isinstance(live.get("sha256"), str):
            entry["sha256"] = live["sha256"]
        return entry
    prev = live.get("previous")
    if isinstance(prev, dict) and isinstance(prev.get("version"), str) and isinstance(prev.get("url"), str):
        return prev
    return None


def built_at_iso() -> str:
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    if epoch and epoch.isdigit():
        now = _dt.datetime.fromtimestamp(int(epoch), tz=_dt.timezone.utc)
    else:
        now = _dt.datetime.now(tz=_dt.timezone.utc)
    return now.strftime("%Y-%m-%dT%H:%M:%SZ")


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Build lag-lens.zip and the Pages site.")
    ap.add_argument(
        "--out",
        default=None,
        help="output directory; relative to the current directory (default: <repo>/site)",
    )
    ap.add_argument("--strict", action="store_true", help="fail if any distributable file is missing")
    ap.add_argument("--repo", default=None, help="repository root (default: parent of this script's dir)")
    ap.add_argument("--base-url", default=DEFAULT_BASE_URL, help="public site base URL for version.json")
    ap.add_argument(
        "--previous",
        default=None,
        metavar="LIVE_VERSION_JSON",
        help="path to the version.json currently live on the site; fills version.json['previous'] for rollback",
    )
    args = ap.parse_args(argv)

    repo = Path(args.repo).resolve() if args.repo else Path(__file__).resolve().parent.parent
    out = (Path(args.out) if args.out else repo / "site").resolve()
    out.mkdir(parents=True, exist_ok=True)

    version = read_version(repo)
    ensure_version_py(repo, version)

    members, missing = collect_members(repo)
    for m in missing:
        warn("missing from the tree, skipped: %s" % m)
    if missing and args.strict:
        print("make_zip: --strict and %d file(s) missing; aborting" % len(missing), file=sys.stderr)
        return 2

    date_time = zip_date_time(repo)
    out_zip = out / ZIP_NAME
    build_zip(members, out_zip, date_time)
    digest = sha256_of(out_zip)

    versioned = out / ("lag-lens-%s.zip" % version)
    shutil.copyfile(out_zip, versioned)

    (out / (ZIP_NAME + ".sha256")).write_text("%s  %s\n" % (digest, ZIP_NAME), encoding="utf-8")
    (out / "VERSION").write_text(version + "\n", encoding="utf-8")

    built_at = built_at_iso()
    base = args.base_url.rstrip("/")
    previous: Optional[dict] = None
    if args.previous:
        live = load_live_version_json(Path(args.previous))
        if live is not None:
            previous = previous_entry(live, version, base)
    version_json = {
        "version": version,
        "sha256": digest,
        "built_at": built_at,
        "url": base + "/" + ZIP_NAME,
        "zip_name": versioned.name,
        # The release before this one, kept on the site for `--update --version X`
        # rollback: {"version", "url", "sha256"} or null for the first release.
        "previous": previous,
    }
    (out / "version.json").write_text(json.dumps(version_json, indent=2) + "\n", encoding="utf-8")

    get_sh = repo / "get.sh"
    if get_sh.is_file():
        if get_sh.resolve() != (out / "get.sh").resolve():
            shutil.copyfile(get_sh, out / "get.sh")
        os.chmod(out / "get.sh", 0o755)

    site_src = repo / "site"
    css = site_src / "style.css"
    if css.is_file() and css.resolve() != (out / "style.css").resolve():
        shutil.copyfile(css, out / "style.css")

    template = site_src / "index.html.tmpl"
    if template.is_file():
        render_index(
            template,
            out / "index.html",
            {
                "VERSION": html.escape(version),
                "BUILT_AT": html.escape(built_at),
                "SHA256": digest,
                "CHANGELOG": changelog_excerpt(repo, version),
                "BASE_URL": html.escape(base),
            },
        )
    else:
        warn("site/index.html.tmpl not found; index.html not rendered")
        if args.strict:
            return 2

    info("version %s, %d members, sha256 %s" % (version, len(members), digest))
    info("wrote %s" % out_zip)
    return 0


if __name__ == "__main__":
    sys.exit(main())
